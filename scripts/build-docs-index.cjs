// Refresh the offline Markdown snapshot after editing or adding documentation.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../docs');
function collect(directory) {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap(entry => {
    const full = path.join(directory, entry.name);
    return entry.isDirectory() ? collect(full) : entry.name.endsWith('.md') ? [full] : [];
  });
}
const documents = collect(root).sort().map(full => {
  const file = path.relative(root, full).replaceAll('\\', '/');
  const content = fs.readFileSync(full, 'utf8');
  const title = content.match(/^#\s+(.+)$/m)?.[1].trim() || file;
  return { file, title, content };
});
fs.mkdirSync(path.join(root, 'assets'), { recursive: true });
fs.writeFileSync(path.join(root, 'assets/documents.js'), '// Generated by node scripts/build-docs-index.cjs\nwindow.DOCS_SNAPSHOT = ' + JSON.stringify(documents).replaceAll('<', '\\u003c') + ';\n');
console.log(`Updated offline documentation: ${documents.length} Markdown files.`);
